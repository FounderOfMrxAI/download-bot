NAME_HINTS = {"turkish": "tr", "german": "de", "spanish": "es", "english": "en"}
WINDOWS_IDS = {0x1F: "tr", 0x07: "de", 0x0A: "es", 0x09: "en"}


def detect_language():
    if sys.platform.startswith("win"):
        try:
            import ctypes

            primary = ctypes.windll.kernel32.GetUserDefaultUILanguage() & 0xFF
            return WINDOWS_IDS.get(primary, "en")
        except Exception:
            pass

    code = ""
    try:
        code = (locale.getlocale()[0] or "").lower()
    except Exception:
        code = ""
    if not code:
        code = (os.environ.get("LANG") or os.environ.get("LANGUAGE") or "").lower()

    for name, short in NAME_HINTS.items():
        if code.startswith(name):
            return short
    prefix = code[:2]
    return prefix if prefix in LANGUAGES else "en"
